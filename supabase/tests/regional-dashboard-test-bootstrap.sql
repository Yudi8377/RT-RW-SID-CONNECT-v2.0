CREATE TABLE public.roles (
  id uuid PRIMARY KEY,
  role_code text NOT NULL UNIQUE
);
CREATE TABLE public.territories (
  id uuid PRIMARY KEY,
  parent_id uuid REFERENCES public.territories(id),
  territory_type text NOT NULL,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.role_assignments (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL,
  role_id uuid NOT NULL REFERENCES public.roles(id),
  scope_territory_id uuid REFERENCES public.territories(id),
  active boolean NOT NULL DEFAULT true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.rt_service_requests (
  id uuid PRIMARY KEY,
  territory_id uuid NOT NULL REFERENCES public.territories(id),
  status text NOT NULL,
  service_type text NOT NULL DEFAULT 'OTHER',
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.addresses (
  id uuid PRIMARY KEY,
  territory_id uuid REFERENCES public.territories(id),
  address_line text,
  postal_code text
);
CREATE TABLE public.households (
  id uuid PRIMARY KEY,
  household_number_hash text,
  address_id uuid REFERENCES public.addresses(id),
  status text NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE public.persons (
  id uuid PRIMARY KEY,
  full_name text NOT NULL,
  birth_place text,
  birth_date date,
  gender text,
  classification text NOT NULL,
  status text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.rt_infrastructure_assets (
  id uuid PRIMARY KEY,
  territory_id uuid NOT NULL REFERENCES public.territories(id)
);
CREATE TABLE public.assistance_applications (
  id uuid PRIMARY KEY,
  territory_id uuid REFERENCES public.territories(id)
);

