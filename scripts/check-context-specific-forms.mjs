import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const app=readFileSync("app.js","utf8");
assert.match(app,/function contextualFallbackSchema\(\)/);
assert.match(app,/function submenuSpecificSchema\(\)/);
assert.match(app,/familyByContext\[\`\$\{module\}:\$\{sub\}\`\]\|\|familyBySub\[sub\]/,"resolver must prefer module/submenu context");
const moduleBlock=app.match(/const modules=\{([\s\S]*?)\n\};/);
assert.ok(moduleBlock,"navigation registry exists");
const submenuIds=new Set([...moduleBlock[1].matchAll(/\[\s*["']([^"']+)["']\s*,\s*["'][^"']+["']\s*\]/g)].map(m=>m[1]));
assert.ok(submenuIds.size>=100,"broad submenu coverage remains");
const contextBlock=app.match(/const familyByContext=\{([\s\S]*?)\n \};/);
assert.ok(contextBlock,"module-specific form overrides exist");
const contextEntries=[...contextBlock[1].matchAll(/"([^"]+)":"([^"]+)"/g)];
const contextMap=new Map(contextEntries.map(m=>[m[1],m[2]]));
assert.equal(contextMap.get("gpffe:requests"),"dataExchange","GPFFE requests must not reuse citizen service request fields");
assert.equal(contextMap.get("dataquality:queue"),"quality","data-quality queue must use quality fields");
assert.equal(contextMap.get("kecamatan:services"),"serviceQueue","regional service monitoring must use queue fields");
const familyBlock=app.match(/const familyBySub=\{([\s\S]*?)\n \};/);
assert.ok(familyBlock,"submenu fallback registry exists");
const families=[...contextEntries.map(m=>m[2]),...[...familyBlock[1].matchAll(/"([^"]+)":"([^"]+)"/g)].map(m=>m[2])];
const schemaBlock=app.match(/const S=\{([\s\S]*?)\n \};\n if\(module==="rt"/);
assert.ok(schemaBlock,"schema family registry exists");
const defined=new Set([...schemaBlock[1].matchAll(/^\s*([A-Za-z][A-Za-z0-9]*):\[/gm)].map(m=>m[1]));
assert.deepEqual([...new Set(families)].filter(x=>!defined.has(x)),[],"all module-specific and fallback families must resolve");
console.log("Module-specific form-context checks passed.");
